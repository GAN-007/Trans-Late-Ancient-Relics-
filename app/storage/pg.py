"""A PostgreSQL connection with the sqlite3 interface the application uses.

The app's SQL is written for SQLite; this layer translates what differs so every module runs
unchanged on PostgreSQL: ? placeholders, INTEGER PRIMARY KEY AUTOINCREMENT, COLLATE NOCASE
(case-insensitive columns get a unique index on LOWER(col)), INSERT OR IGNORE, BLOB, BEGIN
IMMEDIATE, PRAGMA, executescript and cursor.lastrowid. Integrity errors are re-raised as
sqlite3.IntegrityError so existing error handling keeps working. Requires psycopg 3
(pip install -r requirements-postgres.txt).
"""
from __future__ import annotations

import re
import sqlite3
from typing import Any, Iterable, Sequence

_ID_TABLES: dict[str, bool] = {}


def _split_statements(script: str) -> list[str]:
    return [s.strip() for s in script.split(";") if s.strip()]


def _placeholders(sql: str) -> str:
    """? -> %s outside quoted literals; literal % -> %% (psycopg formats every %)."""
    out, quote = [], None
    for char in sql:
        if quote:
            out.append("%%" if char == "%" else char)
            if char == quote:
                quote = None
        elif char in "'\"":
            quote = char
            out.append(char)
        elif char == "?":
            out.append("%s")
        elif char == "%":
            out.append("%%")
        else:
            out.append(char)
    return "".join(out)


def translate(sql: str) -> tuple[str | None, list[str]]:
    """Return (postgres_sql, extra_statements) or (None, []) for statements with no PostgreSQL meaning."""
    stripped = sql.strip().rstrip(";")
    upper = stripped.upper()
    if upper.startswith("PRAGMA") or upper in {"BEGIN", "BEGIN IMMEDIATE", "BEGIN DEFERRED", "BEGIN EXCLUSIVE"}:
        return None, []
    extra: list[str] = []
    s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", stripped, flags=re.I)
    s = re.sub(r"\bBLOB\b", "BYTEA", s, flags=re.I)
    table = re.match(r"\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)", s, flags=re.I)
    if table:
        for col in re.findall(r"(\w+)\s+TEXT[^,()]*?\bCOLLATE\s+NOCASE", s, flags=re.I):
            extra.append(f"CREATE UNIQUE INDEX IF NOT EXISTS {table.group(1)}_{col}_lower ON {table.group(1)} (LOWER({col}))")
        s = re.sub(r"\bUNIQUE\s+COLLATE\s+NOCASE", "", s, flags=re.I)
        s = re.sub(r"\bCOLLATE\s+NOCASE", "", s, flags=re.I)
        _ID_TABLES[table.group(1).lower()] = bool(re.search(r"\bid\b[^,]*PRIMARY KEY", s, flags=re.I))
    else:
        s = re.sub(r"(\w+(?:\.\w+)?)\s*=\s*\?\s+COLLATE\s+NOCASE", r"LOWER(\1)=LOWER(?)", s, flags=re.I)
    if re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO", s, flags=re.I):
        s = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", s, count=1, flags=re.I) + " ON CONFLICT DO NOTHING"
    if re.match(r"\s*INSERT\s+OR\s+REPLACE", s, flags=re.I):
        raise sqlite3.NotSupportedError("INSERT OR REPLACE has no portable meaning; use INSERT … ON CONFLICT … DO UPDATE")
    return _placeholders(s), extra


class Row:
    """Behaves like sqlite3.Row: index or key access, keys(), iteration over values, dict(row)."""

    __slots__ = ("_keys", "_values", "_index")

    def __init__(self, keys: Sequence[str], values: Sequence[Any]):
        self._keys = list(keys)
        self._values = tuple(bytes(v) if isinstance(v, memoryview) else v for v in values)
        self._index = {k: i for i, k in enumerate(self._keys)}

    def __getitem__(self, key: int | str) -> Any:
        if isinstance(key, (int, slice)):
            return self._values[key]
        return self._values[self._index[key]]

    def keys(self) -> list[str]:
        return list(self._keys)

    def __iter__(self):
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, Row) and self._values == other._values and self._keys == other._keys

    def __repr__(self) -> str:
        return f"Row({dict(zip(self._keys, self._values))!r})"


class Cursor:
    def __init__(self, conn: "Connection"):
        self._conn = conn
        self._cur = conn._raw.cursor()
        self.lastrowid: int | None = None
        self._returned: list[Row] | None = None

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount

    @property
    def description(self):
        return self._cur.description

    def _rows(self, raw: Iterable[Sequence[Any]]) -> list[Row]:
        names = [d.name for d in self._cur.description or []]
        return [Row(names, r) for r in raw]

    def execute(self, sql: str, params: Sequence[Any] | dict = ()) -> "Cursor":
        statement, extra = translate(sql)
        if statement is None:
            return self
        is_insert = bool(re.match(r"\s*INSERT\b", statement, flags=re.I)) and "RETURNING" not in statement.upper()
        target = re.match(r"\s*INSERT\s+INTO\s+(\w+)", statement, flags=re.I)
        wants_id = is_insert and target and _ID_TABLES.get(target.group(1).lower(), self._conn._has_id(target.group(1)))
        if wants_id:
            statement += " RETURNING id"
        try:
            self._cur.execute(statement, tuple(params) if not isinstance(params, dict) else params)
            for more in extra:
                self._cur.execute(more)
        except Exception as exc:
            self._conn._raise(exc)
        self._returned = None
        if wants_id:
            row = self._cur.fetchone()
            self.lastrowid = row[0] if row else None
        return self

    def executemany(self, sql: str, seq: Iterable[Sequence[Any]]) -> "Cursor":
        statement, _ = translate(sql)
        if statement is None:
            return self
        try:
            self._cur.executemany(statement, [tuple(p) for p in seq])
        except Exception as exc:
            self._conn._raise(exc)
        return self

    def fetchone(self) -> Row | None:
        if self._cur.description is None:
            return None
        row = self._cur.fetchone()
        return self._rows([row])[0] if row is not None else None

    def fetchall(self) -> list[Row]:
        if self._cur.description is None:
            return []
        return self._rows(self._cur.fetchall())

    def fetchmany(self, size: int = 1) -> list[Row]:
        if self._cur.description is None:
            return []
        return self._rows(self._cur.fetchmany(size))

    def __iter__(self):
        return iter(self.fetchall())

    def close(self) -> None:
        self._cur.close()


class Connection:
    def __init__(self, raw: Any):
        self._raw = raw
        self.row_factory = None  # accepted for sqlite3 compatibility; rows are always Row objects
        self._id_cache: dict[str, bool] = {}

    def _has_id(self, table: str) -> bool:
        table = table.lower()
        if table not in self._id_cache:
            cur = self._raw.cursor()
            cur.execute("SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name=%s AND column_name='id'",
                        (table,))
            self._id_cache[table] = cur.fetchone() is not None
        return self._id_cache[table]

    def _raise(self, exc: Exception) -> None:
        import psycopg
        self._raw.rollback()
        if isinstance(exc, psycopg.errors.IntegrityError):
            raise sqlite3.IntegrityError(str(exc)) from exc
        if isinstance(exc, psycopg.errors.UndefinedTable):
            raise sqlite3.OperationalError(str(exc)) from exc
        raise exc

    def cursor(self) -> Cursor:
        return Cursor(self)

    def execute(self, sql: str, params: Sequence[Any] | dict = ()) -> Cursor:
        return Cursor(self).execute(sql, params)

    def executemany(self, sql: str, seq: Iterable[Sequence[Any]]) -> Cursor:
        return Cursor(self).executemany(sql, seq)

    def executescript(self, script: str) -> Cursor:
        cur = Cursor(self)
        for statement in _split_statements(script):
            cur.execute(statement)
        self._raw.commit()
        return cur

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()

    def __enter__(self) -> "Connection":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        if exc_type is None:
            self.commit()
        else:
            self.rollback()


def connect(url: str, schema: str | None = None) -> Connection:
    import psycopg
    raw = psycopg.connect(url, connect_timeout=10)
    if schema:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{0,62}", schema):
            raise ValueError("ESHB_DATABASE_SCHEMA must be a plain identifier")
        with raw.cursor() as cur:
            cur.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
            cur.execute(f'SET search_path TO "{schema}"')
        raw.commit()
    return Connection(raw)
